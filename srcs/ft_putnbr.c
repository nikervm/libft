#include "libft.h"

void	ft_putnbr(int n)
{
	int sign;

	if (n >= 10 || n <= -10)
		ft_putnbr(n / 10);
	if (n > -10 && n < 0)
		ft_putchar('-');
	sign = (n > 0) ? 1 : -1;
	ft_putchar(sign * (n % 10) + '0');
}
